\set ON_ERROR_STOP on
\if :allow_demo
\else
  \echo 'Refusing to run: pass -v allow_demo=1 (use scripts/dev/reception-demo.sh).'
  \quit
\endif

-- Remove only the fixed reception demo fixture and artifacts attached to it.
-- Pre-existing guests/reservations (e.g. "ashish") and room DEL-101 are untouched.
BEGIN;

CREATE TEMP TABLE demo_stay_ids AS
SELECT id FROM stay
WHERE id IN (
  'd5000000-0000-4000-8000-000000000002',
  'd5000000-0000-4000-8000-000000000003',
  'd5000000-0000-4000-8000-000000000004'
)
OR reservation_id IN (
  'd4000000-0000-4000-8000-000000000001',
  'd4000000-0000-4000-8000-000000000002',
  'd4000000-0000-4000-8000-000000000003',
  'd4000000-0000-4000-8000-000000000004',
  'd4000000-0000-4000-8000-000000000005',
  'd4000000-0000-4000-8000-000000000006'
);

CREATE TEMP TABLE demo_folio_ids AS
SELECT id FROM folio
WHERE id IN (
  'd6000000-0000-4000-8000-000000000002',
  'd6000000-0000-4000-8000-000000000003',
  'd6000000-0000-4000-8000-000000000004'
)
OR stay_id IN (SELECT id FROM demo_stay_ids);

CREATE TEMP TABLE demo_payment_ids AS
SELECT id FROM payment
WHERE id IN (
  'd8000000-0000-4000-8000-000000000101',
  'd8000000-0000-4000-8000-000000000202',
  'd8000000-0000-4000-8000-000000000303',
  'd8000000-0000-4000-8000-000000000606'
)
OR folio_id IN (SELECT id FROM demo_folio_ids)
OR booking_id IN (
  'd4000000-0000-4000-8000-000000000001',
  'd4000000-0000-4000-8000-000000000002',
  'd4000000-0000-4000-8000-000000000003',
  'd4000000-0000-4000-8000-000000000004',
  'd4000000-0000-4000-8000-000000000005',
  'd4000000-0000-4000-8000-000000000006'
);

CREATE TEMP TABLE demo_room_ids AS
SELECT id FROM room
WHERE id IN (
  'a1010000-0000-0000-0000-000000000002', -- DEL-102
  'a1010000-0000-0000-0000-000000000003', -- DEL-103
  'a1020000-0000-0000-0000-000000000001', -- SUI-201
  'a1020000-0000-0000-0000-000000000003', -- SUI-203
  'a1030000-0000-0000-0000-000000000001', -- VIL-301
  'a1030000-0000-0000-0000-000000000002'  -- VIL-302
)
UNION SELECT room_id FROM stay WHERE id IN (SELECT id FROM demo_stay_ids)
UNION SELECT room_id FROM reservation
  WHERE id IN (
    'd4000000-0000-4000-8000-000000000001',
    'd4000000-0000-4000-8000-000000000002',
    'd4000000-0000-4000-8000-000000000003',
    'd4000000-0000-4000-8000-000000000004',
    'd4000000-0000-4000-8000-000000000005',
    'd4000000-0000-4000-8000-000000000006'
  )
UNION SELECT from_room_id FROM room_transfer WHERE stay_id IN (SELECT id FROM demo_stay_ids)
UNION SELECT to_room_id FROM room_transfer WHERE stay_id IN (SELECT id FROM demo_stay_ids);

DELETE FROM refund WHERE payment_id IN (SELECT id FROM demo_payment_ids);
DELETE FROM invoice WHERE folio_id IN (SELECT id FROM demo_folio_ids);
DELETE FROM payment WHERE id IN (SELECT id FROM demo_payment_ids);
DELETE FROM folio_entry WHERE folio_id IN (SELECT id FROM demo_folio_ids);
DELETE FROM folio WHERE id IN (SELECT id FROM demo_folio_ids);
DELETE FROM room_transfer WHERE stay_id IN (SELECT id FROM demo_stay_ids);
DELETE FROM housekeeping_task
WHERE id IN (
  'd9000000-0000-4000-8000-000000000101',
  'd9000000-0000-4000-8000-000000000202',
  'd9000000-0000-4000-8000-000000000303'
)
OR room_id IN (SELECT id FROM demo_room_ids);
DELETE FROM stay WHERE id IN (SELECT id FROM demo_stay_ids);
DELETE FROM reservation_hold WHERE reservation_id IN (
  'd4000000-0000-4000-8000-000000000001',
  'd4000000-0000-4000-8000-000000000002',
  'd4000000-0000-4000-8000-000000000003',
  'd4000000-0000-4000-8000-000000000004',
  'd4000000-0000-4000-8000-000000000005',
  'd4000000-0000-4000-8000-000000000006'
);
DELETE FROM reservation WHERE id IN (
  'd4000000-0000-4000-8000-000000000001',
  'd4000000-0000-4000-8000-000000000002',
  'd4000000-0000-4000-8000-000000000003',
  'd4000000-0000-4000-8000-000000000004',
  'd4000000-0000-4000-8000-000000000005',
  'd4000000-0000-4000-8000-000000000006'
);
DELETE FROM loyalty_ledger WHERE member_id IN (
  SELECT id FROM member WHERE guest_id IN (
    'd0000000-0000-4000-8000-000000000001',
    'd0000000-0000-4000-8000-000000000002',
    'd0000000-0000-4000-8000-000000000003',
    'd0000000-0000-4000-8000-000000000004',
    'd0000000-0000-4000-8000-000000000005',
    'd0000000-0000-4000-8000-000000000006'
  )
);
DELETE FROM member WHERE guest_id IN (
  'd0000000-0000-4000-8000-000000000001',
  'd0000000-0000-4000-8000-000000000002',
  'd0000000-0000-4000-8000-000000000003',
  'd0000000-0000-4000-8000-000000000004',
  'd0000000-0000-4000-8000-000000000005',
  'd0000000-0000-4000-8000-000000000006'
);
DELETE FROM guest_communication WHERE guest_id IN (
  'd0000000-0000-4000-8000-000000000001',
  'd0000000-0000-4000-8000-000000000002',
  'd0000000-0000-4000-8000-000000000003',
  'd0000000-0000-4000-8000-000000000004',
  'd0000000-0000-4000-8000-000000000005',
  'd0000000-0000-4000-8000-000000000006'
);
DELETE FROM guest WHERE id IN (
  'd0000000-0000-4000-8000-000000000001',
  'd0000000-0000-4000-8000-000000000002',
  'd0000000-0000-4000-8000-000000000003',
  'd0000000-0000-4000-8000-000000000004',
  'd0000000-0000-4000-8000-000000000005',
  'd0000000-0000-4000-8000-000000000006'
);

-- Only fixture-affected rooms are restored; any non-fixture active stay keeps its room occupied.
UPDATE room r SET status = 'ready'
WHERE r.id IN (SELECT id FROM demo_room_ids)
  AND NOT EXISTS (
    SELECT 1 FROM stay s WHERE s.room_id = r.id AND s.status = 'checked-in'
  );

COMMIT;
\echo 'Reception demo fixture removed.'
