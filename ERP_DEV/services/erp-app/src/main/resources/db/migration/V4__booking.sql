-- V4: booking engine — rooms, rates, promos, reservations, holds + seed.
-- Forward-only (never edit after apply). Portable SQL (Postgres + H2-PG-mode).
-- Model: guests hold a CATEGORY (availability pool); physical rooms are
-- assigned at check-in (3.3). Money in paise; all policy numbers live in
-- app_config (V2) — this script only seeds reference catalogue data.

CREATE TABLE room (
  id UUID PRIMARY KEY,
  property_id UUID NOT NULL REFERENCES property (id),
  category_id UUID NOT NULL REFERENCES room_category (id),
  room_no VARCHAR(20) NOT NULL,
  status VARCHAR(50) NOT NULL DEFAULT 'ready',
  CONSTRAINT uq_room_property_no UNIQUE (property_id, room_no)
);
CREATE INDEX idx_room_category_status ON room (category_id, status);

CREATE TABLE rate_plan (
  id UUID PRIMARY KEY,
  property_id UUID NOT NULL REFERENCES property (id),
  category_id UUID NOT NULL REFERENCES room_category (id),
  name VARCHAR(200) NOT NULL,
  multiplier_bps INT NOT NULL,
  dow_mask VARCHAR(50) NOT NULL DEFAULT 'MON,TUE,WED,THU,FRI,SAT,SUN',
  from_date DATE NOT NULL,
  to_date DATE NOT NULL
);

CREATE TABLE promo (
  id UUID PRIMARY KEY,
  property_id UUID NOT NULL REFERENCES property (id),
  code VARCHAR(50) NOT NULL,
  pct_bps INT NOT NULL,
  valid_from DATE NOT NULL,
  valid_to DATE NOT NULL,
  max_uses INT NOT NULL DEFAULT 1000000,
  used_count INT NOT NULL DEFAULT 0,
  CONSTRAINT uq_promo_property_code UNIQUE (property_id, code)
);

CREATE TABLE reservation (
  id UUID PRIMARY KEY,
  property_id UUID NOT NULL REFERENCES property (id),
  guest_id UUID NOT NULL REFERENCES guest (id),
  category_id UUID NOT NULL REFERENCES room_category (id),
  room_id UUID REFERENCES room (id),
  checkin_date DATE NOT NULL,
  checkout_date DATE NOT NULL,
  nights INT NOT NULL,
  quoted_total_paise BIGINT NOT NULL,
  advance_due_paise BIGINT NOT NULL DEFAULT 0,
  cancellation_fee_paise BIGINT NOT NULL DEFAULT 0,
  status VARCHAR(50) NOT NULL DEFAULT 'hold',
  source VARCHAR(50) NOT NULL DEFAULT 'web',
  idempotency_key VARCHAR(200) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_reservation_idem UNIQUE (property_id, idempotency_key),
  CONSTRAINT chk_reservation_dates CHECK (checkout_date > checkin_date)
);
CREATE INDEX idx_res_category_dates ON reservation (category_id, checkin_date, checkout_date, status);
CREATE INDEX idx_res_guest ON reservation (guest_id, status);

CREATE TABLE reservation_hold (
  reservation_id UUID PRIMARY KEY REFERENCES reservation (id),
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_hold_expires ON reservation_hold (expires_at);

